#!/usr/bin/env bash
# Sources key from .env; all output redacted.
cd "$(dirname "$0")/.."
set -a; . ./.env; set +a
BASE=$EOA_API_BASE_URL
t() { # label, then curl args (path first)
  local label=$1; shift
  printf '%-34s ' "$label"
  curl -sS -m 20 -w ' [%{http_code}] %{content_type}' "$@" | tr '\n' ' '; echo
}
F() { t "$1" -X POST "$BASE$2" "${@:3}"; }
echo "== baseline"
F "list (empty)" /games/list -d "api_key=$EOA_API_KEY"
t "lastGameId (empty)" "$BASE/lastGameId?api_key=$EOA_API_KEY"
echo "== add"
F "add Zelda" /games/add -d "api_key=$EOA_API_KEY" -d "name=Zelda"
F "add Zelda again (dup)" /games/add -d "api_key=$EOA_API_KEY" -d "name=Zelda"
F "add zelda (case)" /games/add -d "api_key=$EOA_API_KEY" -d "name=zelda"
F "add '  Zelda  ' (space)" /games/add -d "api_key=$EOA_API_KEY" --data-urlencode "name=  Zelda  "
F "add empty name" /games/add -d "api_key=$EOA_API_KEY" -d "name="
F "add missing name" /games/add -d "api_key=$EOA_API_KEY"
F "add html" /games/add -d "api_key=$EOA_API_KEY" --data-urlencode "name=<b>Mario</b> & Co"
F "add unicode" /games/add -d "api_key=$EOA_API_KEY" --data-urlencode "name=Pokémon 日本"
F "add 300 chars" /games/add -d "api_key=$EOA_API_KEY" --data-urlencode "name=$(printf 'a%.0s' {1..300})"
F "add via JSON body" /games/add -H 'Content-Type: application/json' -d "{\"api_key\":\"$EOA_API_KEY\",\"name\":\"JsonGame\"}"
t "add via GET" "$BASE/games/add?api_key=$EOA_API_KEY&name=GetGame"
echo "== list/search"
F "list" /games/list -d "api_key=$EOA_API_KEY"
F "search 1" /games/search -d "api_key=$EOA_API_KEY" -d "id=1"
F "search 9999 (unknown)" /games/search -d "api_key=$EOA_API_KEY" -d "id=9999"
F "search id=abc" /games/search -d "api_key=$EOA_API_KEY" -d "id=abc"
F "search no id" /games/search -d "api_key=$EOA_API_KEY"
echo "== votes"
F "vote 1" /games/vote -d "api_key=$EOA_API_KEY" -d "id=1"
F "vote 1 again" /games/vote -d "api_key=$EOA_API_KEY" -d "id=1"
F "search 1 (votes?)" /games/search -d "api_key=$EOA_API_KEY" -d "id=1"
F "removeVote 1" /games/removeVote -d "api_key=$EOA_API_KEY" -d "id=1"
F "removeVote 1" /games/removeVote -d "api_key=$EOA_API_KEY" -d "id=1"
F "removeVote 1 (below 0?)" /games/removeVote -d "api_key=$EOA_API_KEY" -d "id=1"
F "search 1 (votes?)" /games/search -d "api_key=$EOA_API_KEY" -d "id=1"
F "vote 9999 (unknown)" /games/vote -d "api_key=$EOA_API_KEY" -d "id=9999"
F "removeVote 9999 (unknown)" /games/removeVote -d "api_key=$EOA_API_KEY" -d "id=9999"
echo "== remove / ids"
t "lastGameId" "$BASE/lastGameId?api_key=$EOA_API_KEY"
F "remove 2" /games/remove -d "api_key=$EOA_API_KEY" -d "id=2"
F "remove 2 again" /games/remove -d "api_key=$EOA_API_KEY" -d "id=2"
F "search 2 (removed)" /games/search -d "api_key=$EOA_API_KEY" -d "id=2"
F "vote 2 (removed)" /games/vote -d "api_key=$EOA_API_KEY" -d "id=2"
t "lastGameId after remove" "$BASE/lastGameId?api_key=$EOA_API_KEY"
F "add after remove" /games/add -d "api_key=$EOA_API_KEY" -d "name=Zelda2"
F "list" /games/list -d "api_key=$EOA_API_KEY"
echo "== auth/method errors"
F "list no key" /games/list
F "list bad key" /games/list -d "api_key=badkey"
t "lastGameId no key" "$BASE/lastGameId"
t "list via GET" "$BASE/games/list?api_key=$EOA_API_KEY"
t "unknown route" "$BASE/nope"
echo "== flush"
F "flush" /cache/flush -d "api_key=$EOA_API_KEY"
F "list after flush" /games/list -d "api_key=$EOA_API_KEY"
F "add after flush" /games/add -d "api_key=$EOA_API_KEY" -d "name=Fresh"
t "lastGameId after flush" "$BASE/lastGameId?api_key=$EOA_API_KEY"
F "flush (cleanup)" /cache/flush -d "api_key=$EOA_API_KEY"
